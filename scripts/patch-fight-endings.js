for (const [id, ending] of Object.entries(endings)) {
    const paragraph = ps[id];
    if (!paragraph) throw new Error(`Не найден узел ${id}`);
    if (paragraph.text.startsWith(ending)) continue;
    paragraph.text = `${ending}\n\n${paragraph.text}`;
}

for (const [id, text] of Object.entries(personalEndings)) {
    const paragraph = ps[id];
    if (!paragraph) throw new Error(`Не найден узел ${id}`);
    paragraph.text = text;
}

