function howToPlayBlock() {
    return `<h3>Как вести бой</h3>
Можно сыграть по полным правилам PF2E (статблок выше — эталон), а можно провести бой по сценарию раундов ниже: каждый раунд описывает, что делает противник, что бросать (навык или спасбросок, DC) и чем кончается успех или провал. Броски делаете сами за столом или в dice-roller.

Если бросать совсем не хочется — <strong>«Быстрый исход»</strong> в конце узла: отнимите у каждого героя столько HP и идите к добыче.`;
}

function fastBlock(enemy) {
    const rows = enemy.fastDamage.map(line => `• ${line}`).join('\n');
    return `<h3>Быстрый исход (без бросков)</h3>
Отнимите у каждого героя примерно столько (типичный бой; в скобках — если повезёт противнику):
${rows}

${enemy.fastNote}`;
}

