function buildFight(fight) {
    const prefix = `TEST-${fight.key}`;
    const ids = fight.rounds.map((_, index) => `${prefix}-${index + 1}`);
    const winId = `${prefix}-WIN`;
    const defeatId = `${prefix}-DEFEAT`;
    const timeoutId = `${prefix}-TIMEOUT`;
    const hasSurprise = Boolean(fight.surpriseDC);
    const paragraphs = {};

    fight.rounds.forEach((round, index) => {
        const roundNumber = index + 1;
        const isFirst = index === 0;
        const nextTarget = ids[index + 1] || timeoutId;
        const isPhase2Start = Boolean(fight.phase2From && roundNumber === fight.phase2From);
        const isPhase1 = !fight.phase2From || roundNumber < fight.phase2From;
        const zeroTarget = isPhase1 && fight.phase2From ? ids[fight.phase2From - 1] : null;
        const currentHpMax = fight.phase2From && roundNumber >= fight.phase2From
            ? fight.phase2Hp
            : fight.hp;
        const combat = {
            fightId: fight.id,
            enemyName: fight.name,
            enemyHpMax: currentHpMax,
            enemyAc: fight.ac,
            round: roundNumber,
            roundsTotal: fight.rounds.length,
            attackDamage: round.attackDamage || fight.damageByRound?.[index] || fight.attackDamage,
            nextTarget,
            victoryTarget: winId,
            defeatTarget: defeatId,
            timeoutTarget: timeoutId,
            action: round.action,
            icon: round.icon,
            hint: round.hint || '',
            // round.image — необязательный отдельный кадр удара; иначе портрет противника.
            image: round.image || fight.image,
            ...(round.controlEffect ? { controlEffect: round.controlEffect } : {}),
            ...(round.buffEffect ? { buffEffect: round.buffEffect } : {}),
            ...(round.debuffEffect ? { debuffEffect: round.debuffEffect } : {}),
            ...(fight.weaknessType ? {
                weaknessType: fight.weaknessType,
                weakness: fight.weakness,
                weaknessLabel: fight.weaknessLabel
            } : {}),
            ...(isFirst && !hasSurprise ? { start: true } : {}),
            ...(zeroTarget ? { zeroTarget } : {}),
            ...(isPhase2Start ? { resetEnemyHp: true, enemyHpMax: fight.phase2Hp, phase: 2 } : {})
        };

        const roundOptions = isFirst
            ? [...round.options, ...ACE_OPTIONS]
            : round.options;

        paragraphs[ids[index]] = {
            text: round.text,
            ...(isFirst ? { addTags: [`Я в бою с ${fight.name}`] } : {}),
            combat,
            choices: roundOptions.map(option => ({
                // В реальной игре видно только действие; DC и урон добавляет движок на тестовом полигоне.
                text: option.text.split(' — ')[0],
                target: nextTarget,
                ...(option.hero ? { requiresHero: option.hero } : {}),
                combatCheck: {
                    skill: option.skill,
                    dc: option.dc,
                    // Урон врагу больше не входит в защиту: его наносит обычный удар героя.
                    failHeroDamage: option.failDamage || combat.attackDamage,
                    ...(option.enemyHeal ? { enemyHeal: option.enemyHeal } : {}),
                    ...(option.heal ? { heal: option.heal } : {}),
                    ...(option.guard ? { guard: true } : {}),
                    ...(option.clearConditions ? { clearConditions: true } : {}),
                    ...(option.dispelBuff ? { dispelBuff: true } : {}),
                    ...(option.interruptBuff ? { interruptBuff: true } : {}),
                    ...(option.expose ? { expose: option.expose } : {}),
                    ...(option.ace ? { ace: true, autoSuccess: true } : {})
                }
            }))
        };
    });

    if (hasSurprise) {
        const surpriseId = `${prefix}-SURPRISE`;
        const phase2Target = fight.phase2From ? ids[fight.phase2From - 1] : null;
        paragraphs[surpriseId] = {
            text: 'Ты обходишь противника тенью и выбираешь момент. Если он не заметит — твой удар придёт до первого раунда.',
            combat: {
                fightId: fight.id,
                enemyName: fight.name,
                enemyHpMax: fight.hp,
                enemyAc: fight.ac,
                round: 0,
                roundsTotal: fight.rounds.length,
                attackDamage: 0,
                nextTarget: ids[0],
                victoryTarget: winId,
                defeatTarget: defeatId,
                timeoutTarget: timeoutId,
                action: 'Внезапная атака',
                icon: '🕶️',
                hint: `Скрытность DC ${fight.surpriseDC}. Успех — бесплатный удар до первого раунда.`,
                image: fight.image,
                start: true,
                surpriseRound: true,
                ...(phase2Target ? { zeroTarget: phase2Target } : {}),
                ...(fight.weaknessType ? {
                    weaknessType: fight.weaknessType,
                    weakness: fight.weakness,
                    weaknessLabel: fight.weaknessLabel
                } : {})
            },
            choices: [{
                text: '🕶️ Ударить из тени',
                target: ids[0],
                combatCheck: {
                    skill: 'Скрытность',
                    dc: fight.surpriseDC,
                    failHeroDamage: 0,
                    surpriseAttack: true
                }
            }]
        };
        fight.surpriseId = surpriseId;
    }

    paragraphs[winId] = {
        text: fight.winText,
        combatEnd: true,
        addTags: [`${fight.name} мёртв`],
        choices: [
            { text: '↩️ Вернуться на полигон', target: 'TEST-HUB' }
        ]
    };

    paragraphs[defeatId] = {
        text: fight.defeatText,
        combatEnd: true,
        choices: [
            { text: `⚔️ Снова в бой с ${fight.name}`, target: ids[0] },
            { text: '↩️ Вернуться на полигон', target: 'TEST-HUB' }
        ]
    };

    paragraphs[timeoutId] = {
        text: fight.timeoutText,
        combatEnd: true,
        choices: [
            { text: `⚔️ Попробовать снова`, target: ids[0] },
            { text: '↩️ Вернуться на полигон', target: 'TEST-HUB' }
        ]
    };

    return paragraphs;
}

