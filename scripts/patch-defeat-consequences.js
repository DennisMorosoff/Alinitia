function unique(values) {
    return [...new Set(values)];
}

function addRequiresNot(choice, tags) {
    choice.requiresNot = unique([...(choice.requiresNot || []), ...tags]);
}

function addRequiresQuest(choice, requirement) {
    const list = choice.requiresQuest || [];
    const exists = list.some(item => item.id === requirement.id && item.state === requirement.state);
    choice.requiresQuest = exists ? list : [...list, requirement];
}

function gateChoice(nodeId, target, tags) {
    const node = ps[nodeId];
    if (!node) throw new Error(`Не найден узел ${nodeId}`);
    const matches = (node.choices || []).filter(choice => choice.target === target);
    if (matches.length !== 1) {
        throw new Error(`В ${nodeId} ожидался ровно один переход на ${target}, найдено ${matches.length}`);
    }
    addRequiresNot(matches[0], tags);
}

function addConditionalText(nodeId, block) {
    const node = ps[nodeId];
    if (!node) throw new Error(`Не найден узел ${nodeId}`);
    node.conditionalTexts = node.conditionalTexts || [];
    const exists = node.conditionalTexts.some(item => item.text === block.text);
    if (!exists) node.conditionalTexts.push(block);
}

const defeatQuest = foe => ({
    id: foe.quest,
    state: 'провален',
    fromStates: ['выдан']
});

const hubByScene = {
    '005': 'H06',
    '086': 'H02',
    '087': 'H04',
    '088': 'H06',
    '089': 'H05'
};

for (const foe of foes) {
    const defeat = ps[foe.defeat];
    const fight = ps[foe.fight];
    const loot = ps[foe.loot];
    if (!defeat || !fight || !loot) {
        throw new Error(`Не найдена тройка боевых узлов для ${foe.name}`);
    }

    // Поражение: довольное лицо, уход со сцены, сон.
    defeat.text = foe.text;
    defeat.addTags = unique([...(defeat.addTags || []), foe.goneTag]);
    defeat.setQuest = defeatQuest(foe);

    // Победа подтверждает смерть только в узле добычи.
    fight.addTags = (fight.addTags || []).filter(tag => tag !== foe.deadTag);
    loot.addTags = unique([...(loot.addTags || []), foe.deadTag]);
    loot.setQuest = defeatQuest(foe);

    // Противник исчезает из игры так же, как после победы.
    const gone = [foe.deadTag, foe.goneTag];
    const scene = foe.defeat.replace(/-defeat$/, '');
    gateChoice(hubByScene[scene], scene, gone);
}

